import test from 'node:test';
import assert from 'node:assert/strict';
import { createStore } from '../../src/store/index.ts';
import { createAnalyticsConsumer, analyticsRepository } from '../../src/consumers/analytics/index.ts';
import { createReviewer } from '../../src/review/index.ts';
import { config, event, collection, bundle, result } from '../store/fixtures.ts';
const at = '2026-09-30T12:00:00Z';
const ref = (id: string, revision = 1) => ({ schema_version: 1 as const, logical_id: id, revision });
const definition = (id: string, status: 'formal' | 'candidate' = 'formal', revision = 1) => ({ schema_version: 1 as const, definition_ref: ref('capability:' + id, revision), label: id, keywords: [id], status });
async function setup() {
    const c = await config();
    c.project_whitelist = ['a'];
    c.analytics_catalog = { schema_version: 1, capabilities: [definition('design'), definition('verify', 'candidate')], directions: [], project_mappings: [] };
    const s = await createStore(c);
    const events = [event('pair-evidence')];
    await s.saveCollection(collection(events));
    const b = bundle(events);
    await s.saveBundle(b);
    const r = result(b);
    r.pages = [];
    r.candidates[0].analytics_projection.value!.verification = { schema_version: 1, name: 'verified', value: 'yes', subject: 'Roy', verified_at: '2026-09-30T09:00:00Z', event_refs: [{ schema_version: 1, event_id: events[0].event_id }], basis: 'user_explicit_verification' };
    r.candidates[0].analytics_projection.value!.attribution = { actor: 'Roy', responsibility: 'verification', capability_ids: ['design', 'verify'], goal_target_version: 'v1' };
    const accepted = await s.commitReview(r);
    await s.markExportReady(accepted.batch_id, c.data_dir + '/initial.json');
    const consumer = createAnalyticsConsumer(s, c, { now: () => new Date(at) });
    await consumer.consume();
    const repository = analyticsRepository(s);
    const observation = repository.observations()[0];
    const review = async (id: string, action: string, target = observation.observation_ref, pairs?: any[], retracts?: string) => consumer.review({ schema_version: 1, kind: 'review', events: [{ schema_version: 1, review_id: id, target_ref: target, action, correction: action === 'correct' ? 'Only verification responsibility confirmed' : null, evidence_refs: [], created_at: at, ...(pairs ? { selected_pairs: pairs } : {}), ...(retracts ? { retracts_review_id: retracts } : {}) }] });
    const pair = (id: string, revision = 1) => ({ schema_version: 1, observation_ref: observation.observation_ref, capability_ref: ref('capability:' + id, revision) });
    return { c, s, consumer, repository, observation, review, pair };
}
test('activity confirmation is independent from exact responsibility pairs; correction contests only remaining pairs and specific retraction rebuilds', async () => {
    const f = await setup();
    await f.review('activity', 'confirm');
    assert(f.repository.currentOutput('x').overlays.every(p => p.confirmed === false));
    await f.review('design-pair', 'confirm', f.observation.observation_ref, [f.pair('design')]);
    let overlays = f.repository.currentOutput('x').overlays;
    assert.equal(overlays.find(p => p.label === 'design')!.stage, 'formal');
    assert.equal(overlays.find(p => p.label === 'verify')!.confirmed, false);
    await f.review('correction', 'correct', f.observation.observation_ref, [f.pair('verify')]);
    overlays = f.repository.currentOutput('x').overlays;
    assert.equal(overlays.find(p => p.label === 'design')!.contested, true);
    assert.equal(overlays.find(p => p.label === 'verify')!.confirmed, true);
    assert.equal(overlays.find(p => p.label === 'verify')!.stage, 'candidate');
    await f.review('promote-verify', 'confirm', ref('capability:verify'));
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.stage, 'formal');
    await f.review('undo-correction', 'retract', f.observation.observation_ref, undefined, 'correction');
    overlays = f.repository.currentOutput('x').overlays;
    assert.equal(overlays.find(p => p.label === 'design')!.confirmed, true);
    assert.equal(overlays.find(p => p.label === 'verify')!.confirmed, false);
    assert.equal((await f.review('wrong-undo', 'retract', ref('capability:verify'), undefined, 'design-pair'))[0].status, 'pending');
    await f.review('undo-undo', 'retract', f.observation.observation_ref, undefined, 'undo-correction');
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.confirmed, true);
    const outcome = await f.consumer.consume();
    assert.equal(outcome.analytics_pilot!.reviews.confirmed_pairs, 0); // Current incomplete week is outside completed four-week historical range.
    assert(f.repository.reviews().some(e => e.review_id === 'correction'));
    f.s.close();
});
test('candidate definitions and attribution revisions never inherit confirmation; unknown pair is local pending', async () => {
    const f = await setup();
    await f.review('verified-pair', 'confirm', f.observation.observation_ref, [f.pair('verify')]);
    await f.review('formal-one', 'confirm', ref('capability:verify'));
    await f.review('keep-design-only', 'correct', f.observation.observation_ref, [f.pair('design')]);
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.contested, true);
    await f.consumer.review({ schema_version: 1, kind: 'capability_candidate', definition: definition('verify', 'candidate', 2) });
    assert.equal(f.repository.catalog(f.c).capabilities.find(d => d.label === 'verify')!.status, 'candidate');
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.confirmed, false);
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.contested, false);
    assert.equal((await f.review('stale-definition', 'confirm', f.observation.observation_ref, [f.pair('verify')]))[0].status, 'pending');
    await f.review('new-pair', 'confirm', f.observation.observation_ref, [f.pair('verify', 2)]);
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.stage, 'candidate');
    await f.review('formal-two', 'confirm', ref('capability:verify', 2));
    assert.equal(f.repository.currentOutput('x').overlays.find(p => p.label === 'verify')!.stage, 'formal');
    await f.review('undo-formal-two', 'retract', ref('capability:verify', 2), undefined, 'formal-two');
    assert.equal(f.repository.catalog(f.c).capabilities.find(d => d.label === 'verify')!.status, 'candidate');
    assert.equal((await f.review('unknown', 'confirm', f.observation.observation_ref, [f.pair('unknown')]))[0].status, 'pending');
    const prepared = (await createReviewer(f.s, f.c).prepare({ kind: 'weekly', lane: 'history', period: '2026-10-04', cutoff: at }))[0];
    assert.equal(prepared.analysis_context!.analytics_catalog!.capabilities.length, 2);
    f.s.close();
});
test('expired exact contracts remove current notices and cockpit notices without deleting generated history', async () => {
    const f = await setup();
    f.c.goal_whitelist = ['goal:test'];
    const goal = { schema_version: 1, contract_ref: ref('goal:test'), subject: 'Roy', description: 'Confirmed target', target_version: 'v1', deadline: '2026-10-01T00:00:00Z', confirmed: false };
    const decision = { schema_version: 1, contract_ref: ref('decision:test'), subject: 'Roy', goal_ref: goal.contract_ref, valid_from: '2026-09-29T00:00:00Z', valid_to: '2026-10-01T00:00:00Z', trigger: { schema_version: 1, name: 'verified', expected_value: 'yes' }, confirmed: false };
    await f.consumer.review({ schema_version: 1, kind: 'goal_contract', contract: goal });
    await f.review('goal-confirm', 'confirm', goal.contract_ref);
    await f.consumer.review({ schema_version: 1, kind: 'decision_contract', contract: decision });
    await f.review('decision-confirm', 'confirm', decision.contract_ref);
    assert.equal(f.repository.currentOutput('active', f.c, at).notices.length, 1);
    const future = '2026-10-05T12:00:00Z';
    const expired = createAnalyticsConsumer(f.s, f.c, { now: () => new Date(future) });
    const outcome = await expired.consume();
    assert.equal(outcome.status, 'complete');
    assert.equal(outcome.analytics_pilot!.notifications.generated, 1);
    assert.equal(outcome.analytics_pilot!.notifications.active, 0);
    assert.equal(f.repository.currentOutput('expired', f.c, future).notices.length, 0);
    assert.equal(f.repository.confirmedGoals(f.c, future).length, 0);
    const { readFile } = await import('node:fs/promises');
    const page = await readFile(f.c.wiki_root + '/wiki/personal/synthesis/综合_self_analytics_current.md', 'utf8');
    assert(!page.includes('已满足显式重大决策验证条件'));
    assert.equal(f.repository.pilot(f.c, future).notifications.generated, 1);
    f.s.close();
});
test('four-week SQL action audit counts continuation, narrowing and abandonment once and keeps one active action', async () => {
    const f = await setup();
    let clock = '2026-10-05T12:00:00Z';
    const consumer = createAnalyticsConsumer(f.s, f.c, { now: () => new Date(clock) });
    const reviewer = createReviewer(f.s, f.c);
    let evidence: any[] = [];
    for (const [i, week, when] of [[0, '2026-10-04', '2026-10-05T12:00:00Z'], [1, '2026-10-11', '2026-10-12T12:00:00Z'], [2, '2026-10-18', '2026-10-19T12:00:00Z'], [3, '2026-10-25', '2026-10-25T12:00:00Z']] as const) {
        clock = when;
        const b = (await reviewer.prepare({ kind: 'weekly', lane: 'history', period: week, cutoff: clock }))[0];
        const input = b.analysis_context!;
        if (!i)
            evidence = input.facts.map(fact => fact.fact_ref);
        const r = result(b, 'action-week:' + i, false);
        const action = { schema_version: 1, action_ref: ref('action:single', i === 3 ? 3 : i === 2 ? 2 : 1), subject: 'Roy', description: i >= 2 ? 'Narrow verification' : 'One verification', evidence_refs: evidence, state: i === 3 ? 'abandoned' : 'active' };
        r.analysis = { schema_version: 1, snapshot: { schema_version: 1, analysis_ref: input.analysis_ref!, week_end: week, coverage_status: 'partial', observations: input.observation_candidates!, capabilities: [], goal_gaps: [], direction: 'unknown', patterns: [], validation_action: action }, prior_action_disposition: i ? { schema_version: 1, action_ref: input.prior_action!.action_ref, disposition: i === 1 ? 'continue' : i === 2 ? 'narrow' : 'abandon', reason: 'Explicit semantic choice', evidence_refs: evidence } : null, proposed_confirmations: [], freshness_at: clock } as any;
        const accepted = await reviewer.accept(r);
        await f.s.markExportReady(accepted.batch_id, f.c.data_dir + '/action' + i + '.json');
        assert.equal((await consumer.consume()).status, 'complete');
        assert.equal(f.repository.pilot(f.c, clock).actions.active, i === 3 ? 0 : 1);
    }
    assert.deepEqual(f.repository.pilot(f.c, '2026-10-26T12:00:00Z').actions, { continued: 1, narrowed: 1, abandoned: 1, completed: 0, active: 0 });
    const reprepare = (await reviewer.prepare({ kind: 'weekly', lane: 'history', period: '2026-10-25', cutoff: '2026-10-26T12:00:00Z' }))[0];
    assert.equal(reprepare.analysis_context!.prior_action, null); // A closed current-week action cannot resurrect the older week action.
    f.s.close();
});
test('current asOf views never apply future-dated pair confirmation or its later retraction early', async () => {
    const f = await setup();
    const future = '2026-10-02T12:00:00Z';
    await f.consumer.review({ schema_version: 1, kind: 'review', events: [{ schema_version: 1, review_id: 'future-pair', target_ref: f.observation.observation_ref, action: 'confirm', correction: null, evidence_refs: [], created_at: future, selected_pairs: [f.pair('design')] }] });
    assert.equal(f.repository.currentOutput('before', f.c, at).overlays.find(pair => pair.label === 'design')!.confirmed, false);
    assert.equal(f.repository.currentOutput('after', f.c, future).overlays.find(pair => pair.label === 'design')!.confirmed, true);
    await f.consumer.review({ schema_version: 1, kind: 'review', events: [{ schema_version: 1, review_id: 'future-undo', target_ref: f.observation.observation_ref, action: 'retract', correction: null, evidence_refs: [], created_at: '2026-10-03T12:00:00Z', retracts_review_id: 'future-pair' }] });
    assert.equal(f.repository.currentOutput('still-confirmed', f.c, future).overlays.find(pair => pair.label === 'design')!.confirmed, true);
    assert.equal(f.repository.currentOutput('undo-effective', f.c, '2026-10-03T12:00:00Z').overlays.find(pair => pair.label === 'design')!.confirmed, false);
    f.s.close();
});
