import test from 'node:test';
import assert from 'node:assert/strict';
import { writeFile, readFile, mkdir, rm, stat } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { runCli } from '../../src/cli.ts';
import { createStore } from '../../src/store/index.ts';
import { analyticsRepository } from '../../src/consumers/analytics/index.ts';
import { config, collection, bundle, result, event, range } from '../store/fixtures.ts';
import type { ReviewBundle, ReviewResult } from '../../src/contracts/types.ts';

test('CLI typed weekly/monthly/pages publish and all consumers share actual SQLite revisions without private Analytics text', async () => {
  const c = await config(), root = dirname(c.wiki_root), configPath = join(root, 'config.json');
  c.project_whitelist = ['a'];
  c.journal_timezone_timeline = [{ schema_version: 1, effective_from: '1970-01-01T00:00:00Z', timezone: 'Europe/Amsterdam', basis: 'synthetic test' }];
  c.index_commands = { schema_version: 1, lint: { schema_version: 1, executable: process.execPath, args: ['-e', 'process.exit(0)'] }, build_index: { schema_version: 1, executable: process.execPath, args: ['-e', 'process.exit(0)'] }, qmd: { schema_version: 1, executable: process.execPath, args: ['-e', 'process.exit(0)'] } };
  await writeFile(configPath, JSON.stringify(c));
  const cockpit = join(c.wiki_root, 'wiki/personal/synthesis/综合_self_analytics_current.md');
  await mkdir(dirname(cockpit), { recursive: true }); await writeFile(cockpit, '人工职业目标保留。\n');
  const cli = async (args: string[]) => {
    let out = '', err = '';
    const code = await runCli([...args, '--config', configPath], { stdout: value => { out += value; }, stderr: value => { err += value; }, now: () => '2026-10-05T00:00:00Z' });
    assert.equal(code, 0, err); return JSON.parse(out);
  };
  let inputSequence = 0;
  const publish = async (review: ReviewResult) => { const path = join(root, `result-${++inputSequence}.json`); await writeFile(path, JSON.stringify(review)); return cli(['publish', '--input', path]); };
  const prepare = async (kind: string, period: string): Promise<ReviewBundle> => {
    const output = join(root, `${kind}-${inputSequence}`);
    const prepared = await cli(['prepare', '--kind', kind, '--lane', 'history', '--period', period, '--output', output]);
    const path = join(output, prepared.bundles[0]);
    assert.equal((await stat(path)).mode & 0o777, 0o600);
    return JSON.parse(await readFile(path, 'utf8'));
  };
  const store = await createStore(c);
  try {
    const initial = bundle(); await store.saveCollection(collection()); await store.saveBundle(initial);
    const daily = result(initial); daily.pages = [];
    daily.candidates[0].content = 'PRIVATE synthetic household detail and parser work';
    await publish(daily);
    const consumed = await cli(['consume', '--target', 'all']);
    assert.deepEqual(consumed.consumers.map((item: any) => item.target), ['analytics', 'monthly', 'index']);
    assert.ok(consumed.consumers.every((item: any) => item.status === 'complete'));
    const w = await prepare('weekly', '2026-10-04');
    assert.ok(w.analysis_context); assert.ok(!JSON.stringify(w).includes('PRIVATE'));
    const weekly = result(w, 'weekly-cli', false);
    const context = w.analysis_context!;
    weekly.analysis = { schema_version: 1, snapshot: { schema_version: 1, analysis_ref: context.analysis_ref!, week_end: context.week_end, coverage_status: context.coverage_status, observations: context.observation_candidates ?? [], capabilities: [], goal_gaps: [], direction: 'unknown', patterns: ['已投影的合成证据'], validation_action: null }, prior_action_disposition: null, proposed_confirmations: context.observation_candidates?.slice(0, 3).map(item => item.observation_ref) ?? [], freshness_at: '2026-10-05T00:00:00Z' };
    await publish(weekly); await cli(['consume', '--target', 'all']);
    assert.equal(analyticsRepository(store).snapshots().length, 1);
    const oldObservation = analyticsRepository(store).observations()[0];
    const reviewPath = join(root, 'confirmation.json');
    const confirm = async (id: string, action: 'confirm' | 'retract') => { await writeFile(reviewPath, JSON.stringify({ schema_version: 1, kind: 'review', events: [{ schema_version: 1, review_id: id, target_ref: oldObservation.observation_ref, action, correction: null, evidence_refs: oldObservation.evidence_refs, created_at: '2026-10-05T00:00:00Z' }] })); return cli(['analytics-review', '--input', reviewPath]); };
    assert.equal((await confirm('confirm-cli', 'confirm'))[0].status, 'applied');
    assert.equal((await confirm('retract-confirm-cli', 'retract'))[0].status, 'applied');
    const m = await prepare('monthly', '2026-09');
    const monthly = result(m, 'monthly-cli', false);
    monthly.monthly_review = { schema_version: 1, month: '2026-09', summary: '本月核验了解析器。', fact_refs: m.monthly_context!.facts.map(({ fact_id, revision }) => ({ schema_version: 1, fact_id, revision })), supplement_text: '', coverage_status: m.monthly_context!.coverage_status, completed_work_ids: m.monthly_context!.prepared_work_ids };
    await publish(monthly); await cli(['consume', '--target', 'all']);
    const monthlyRemaining = (await store.listWork('prepare_monthly', 'pending')).filter(work => work.payload.month === '2026-09');
    assert.equal(monthlyRemaining.length, 0, JSON.stringify(monthlyRemaining));
    const correctionBundle = bundle([event('cli-correction')], 'cli-correction');
    correctionBundle.existing_facts = await store.readEffectiveFacts({ range });
    await store.saveCollection(collection(correctionBundle.chunks[0].events, 'live', 'cli-correction-source')); await store.saveBundle(correctionBundle);
    const correction = result(correctionBundle, 'cli-correction'); correction.pages = [];
    correction.candidates[0].disposition = 'replace'; correction.candidates[0].target_refs = [oldObservation.evidence_refs[0]];
    correction.candidates[0].analytics_projection.value!.summary = '更正后的解析器证据';
    await publish(correction); await cli(['consume', '--target', 'all']);
    assert.equal(analyticsRepository(store).facts().length, 1);
    assert.equal((await confirm('stale-confirm-cli', 'confirm'))[0].status, 'stale');
    const monthlyBody = await readFile(join(c.wiki_root, 'wiki/personal/journals/reviews/回顾_2026_09.md'), 'utf8');
    assert.match(monthlyBody, /失效/);
    const retractBundle = bundle([event('cli-fact-retract')], 'cli-fact-retract');
    retractBundle.existing_facts = await store.readEffectiveFacts({ range });
    await store.saveCollection(collection(retractBundle.chunks[0].events, 'live', 'cli-retract-source')); await store.saveBundle(retractBundle);
    const retract = result(retractBundle, 'cli-fact-retract'); retract.pages = [];
    retract.candidates[0].disposition = 'retract'; retract.candidates[0].target_refs = [{ schema_version: 1, fact_id: oldObservation.evidence_refs[0].fact_id, revision: 2 }];
    await publish(retract); await cli(['consume', '--target', 'all']);
    assert.equal(analyticsRepository(store).facts().length, 0);
    assert.equal((await store.readEffectiveFacts({ range })).length, 0);
    assert.ok(!(await readFile(cockpit, 'utf8')).includes('PRIVATE'));
    const health = await cli(['validate', '--scope', 'all']);
    assert.equal(health.status, 'valid'); assert.ok(health.pending.length > 0, 'ordinary semantic preparation debt is not invalid database state');
    const projectPath = 'wiki/projects/项目_synthetic.md', logPath = 'log.md';
    await mkdir(dirname(join(c.wiki_root, projectPath)), { recursive: true });
    await writeFile(join(c.wiki_root, projectPath), '人工项目正文\n' + 'x'.repeat(20000)); await writeFile(join(c.wiki_root, logPath), '人工日志\n');
    const pagesPath = join(root, 'pages.json'); await writeFile(pagesPath, JSON.stringify({ schema_version: 1, paths: [projectPath, logPath] }));
    const pageOutput = join(root, 'pages-material');
    const pagePreparation = await cli(['prepare', '--kind', 'daily', '--lane', 'live', '--period', '2026-09-30', '--pages', pagesPath, '--output', pageOutput]);
    const pageBundle: ReviewBundle = JSON.parse(await readFile(join(pageOutput, pagePreparation.bundles[0]), 'utf8'));
    assert.equal(pageBundle.baselines.find(page => page.path === projectPath)?.context_excerpt, true);
    const pageResult = result(pageBundle, 'pages-cli', false);
    pageResult.pages = [projectPath, logPath].map((path, index) => ({ schema_version: 1, suggestion_id: 'explicit:' + index, date: '2026-09-30', path, baseline_digest: pageBundle.baselines.find(page => page.path === path)!.digest, mode: 'append', old_text: null, new_text: '\n已审阅的合成局部更新。\n', candidate_ids: [] }));
    await publish(pageResult);
    assert.ok((await readFile(join(c.wiki_root, projectPath), 'utf8')).startsWith('人工项目正文'));
    assert.ok((await readFile(join(c.wiki_root, logPath), 'utf8')).includes('已审阅的合成局部更新'));
    assert.equal((await cli(['validate', '--scope', 'changed'])).status, 'valid');
  } finally { store.close(); await rm(root, { recursive: true, force: true }); }
});
