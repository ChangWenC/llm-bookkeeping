import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { createStore } from '../../src/store/index.ts';
import { createReviewer } from '../../src/review/index.ts';
import { digest, canonical } from '../../src/analytics/serialization.ts';
import { config, result } from '../store/fixtures.ts';
const cutoff = '2026-10-05T00:00:00Z';
async function archive(s: any, c: any, id: string, body: string, date = '2026-09-01') {
    const path = 'wiki/personal/journals/archives/v2/2026-09/' + id + '.json';
    const record = { schema_version: 1, format: 'daily-journal-archive-v2', date, source_path: 'wiki/personal/journals/' + id + '.md', original_digest: digest(Buffer.from(body)), original_bytes_base64: Buffer.from(body).toString('base64'), locator: 'archive:' + id, fact_refs: [] };
    await mkdir(dirname(join(c.wiki_root, path)), { recursive: true });
    await writeFile(join(c.wiki_root, path), canonical(record));
    await s.enqueueWork({ schema_version: 1, work_id: id, kind: 'archive_context', lane: 'history', state: 'pending', payload: { month: '2026-09', date, archive_path: path, locator: record.locator, fact_refs: [] }, reason: null, migration_key: null, updated_at: '2026-09-30T10:00:00Z' });
    return path;
}
function monthly(b: any, id: string) { const r = result(b, id, false); r.monthly_review = { schema_version: 1, month: '2026-09', summary: 'Accepted ' + id, supplement_text: '', fact_refs: [], coverage_status: 'partial', completed_archive_context_ids: b.monthly_context.archive_contexts.filter((x: any) => !x.excerpt_reason).map((x: any) => x.work_id) }; return r; }
test('zero-fact distinct original and explicit page material accumulates, exact full IDs survive, replay does not append twice', async () => {
    const c = await config();
    const s = await createStore(c);
    const reviewer = createReviewer(s, c);
    await archive(s, c, 'original-one', 'First original evidence');
    await archive(s, c, 'original-two', 'Second original evidence');
    const a = (await reviewer.prepare({ kind: 'monthly', lane: 'history', period: '2026-09', cutoff, archive_context_offset: 0 }))[0];
    assert.equal(a.monthly_context!.facts.length, 0);
    assert.equal(a.monthly_context!.archive_contexts![0].content_excerpt, 'First original evidence');
    const first = await reviewer.accept(monthly(a, 'one'));
    await s.markExportReady(first.batch_id, c.data_dir + '/one.json');
    await s.completeWork('original-one');
    await archive(s, c, 'late-backdated', 'Should not enter frozen material');
    const b = (await reviewer.prepare({ kind: 'monthly', lane: 'history', period: '2026-09', cutoff, fact_snapshot: a.monthly_context!.facts_page!.snapshot_id, archive_context_offset: 1 }))[0];
    assert.equal(b.monthly_context!.archive_context_page!.total, 2);
    assert.deepEqual(b.monthly_context!.archive_contexts!.map(x => x.work_id), ['original-two']);
    const second = await reviewer.accept(monthly(b, 'two'));
    const artifact = (await s.listOutbox()).find(x => x.batch_id === second.batch_id)!.artifact;
    assert.equal(artifact.monthly_review!.summary, 'Accepted one\n\nAccepted two');
    assert.deepEqual(new Set(artifact.monthly_review!.completed_archive_context_ids), new Set(['original-one', 'original-two']));
    const replay = await reviewer.accept({ ...monthly(b, 'two'), result_id: 'different-model-result' });
    assert(replay.reused);
    const path = 'wiki/projects/context.md';
    await mkdir(dirname(join(c.wiki_root, path)), { recursive: true });
    await writeFile(join(c.wiki_root, path), 'Explicit context third');
    const third = (await reviewer.prepare({ kind: 'monthly', lane: 'history', period: '2026-09', cutoff, fact_snapshot: a.monthly_context!.facts_page!.snapshot_id, page_paths: [path], archive_context_offset: 2 }))[0];
    const accepted = await reviewer.accept(monthly(third, 'three'));
    assert((await s.listOutbox()).find(x => x.batch_id === accepted.batch_id)!.artifact.monthly_review!.summary.includes('Accepted one\n\nAccepted two\n\nAccepted three'));
    s.close();
});
test('excerpt is never acknowledged; increasing the explicit budget exposes the original tail; corrupt archive is local pending', async () => {
    const c = await config();
    c.limits.bundle_bytes = 8192;
    const s = await createStore(c);
    const reviewer = createReviewer(s, c);
    const body = 'Professional original ' + 'x'.repeat(7000) + ' ORIGINAL_TAIL';
    await archive(s, c, 'large', body);
    const bad = await archive(s, c, 'corrupt', 'bad');
    const json = JSON.parse(await (await import('node:fs/promises')).readFile(join(c.wiki_root, bad), 'utf8'));
    json.original_digest = '0'.repeat(64);
    await writeFile(join(c.wiki_root, bad), JSON.stringify(json));
    const b = (await reviewer.prepare({ kind: 'monthly', lane: 'history', period: '2026-09', cutoff }))[0];
    assert(Buffer.byteLength(canonical(b)) <= 8192);
    assert(b.unfinished.some(x => x.reason.includes('digest mismatch')));
    const original = b.monthly_context!.archive_contexts![0];
    assert(original.excerpt_reason?.includes('limits.bundle_bytes'));
    assert(!original.content_excerpt.includes('ORIGINAL_TAIL'));
    const invalid = monthly(b, 'invalid');
    invalid.monthly_review.completed_archive_context_ids = ['large'];
    await assert.rejects(reviewer.accept(invalid), /fully displayed/);
    c.limits.bundle_bytes = 40000;
    const full = (await reviewer.prepare({ kind: 'monthly', lane: 'history', period: '2026-09', cutoff, fact_snapshot: b.monthly_context!.facts_page!.snapshot_id }))[0];
    assert(full.monthly_context!.archive_contexts![0].content_excerpt.endsWith('ORIGINAL_TAIL'));
    assert.equal(full.monthly_context!.archive_contexts![0].excerpt_reason, null);
    assert.equal((await reviewer.accept(monthly(full, 'full'))).facts.length, 0);
    s.close();
});
